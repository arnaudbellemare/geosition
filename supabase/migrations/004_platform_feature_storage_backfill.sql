-- GEOSITION Platform feature storage backfill.
--
-- This migration is intentionally idempotent. It covers Supabase projects that
-- applied an older copy of 002_geo_platform.sql before durable page audits and
-- weekly evidence reports were added to the platform schema.

create table if not exists public.geo_page_audits (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  run_id bigint not null references public.geo_platform_runs(id) on delete cascade,
  domain text not null,
  page_url text not null,
  sitemap_url text not null default '',
  score int not null default 0,
  band text not null default '',
  http_status int,
  error text not null default '',
  score_breakdown_json jsonb not null default '{}'::jsonb,
  title_issues_json jsonb not null default '[]'::jsonb,
  meta_issues_json jsonb not null default '[]'::jsonb,
  schema_issues_json jsonb not null default '[]'::jsonb,
  recommendations_json jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_geo_page_audits_org_domain
on public.geo_page_audits (org_id, domain, created_at desc);

create index if not exists idx_geo_page_audits_org_page
on public.geo_page_audits (org_id, page_url, created_at desc);

create index if not exists idx_geo_page_audits_run
on public.geo_page_audits (run_id);

alter table public.geo_page_audits enable row level security;

create table if not exists public.geo_weekly_evidence_runs (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  domain text not null,
  period_start text not null,
  period_end text not null,
  status text not null default 'completed',
  score int,
  band text not null default '',
  metrics_json jsonb not null default '[]'::jsonb,
  action_plan_json jsonb not null default '{}'::jsonb,
  artifact_json_uri text not null default '',
  artifact_html_uri text not null default '',
  summary text not null default '',
  generated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists idx_geo_weekly_evidence_org_domain
on public.geo_weekly_evidence_runs (org_id, domain, generated_at desc);

alter table public.geo_weekly_evidence_runs enable row level security;

alter table public.geo_agent_usage_events
add column if not exists evidence_artifact_id text not null default '';
