-- GEO Platform: multi-tenant workspace (production / Supabase)
-- Apply with Supabase CLI or SQL editor. Service role bypasses RLS for server-side API.

create table if not exists public.geo_platform_users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  email_domain text not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.geo_organizations (
  id bigint generated by default as identity primary key,
  name text not null,
  email_domain text not null,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.geo_memberships (
  user_id bigint not null references public.geo_platform_users(id) on delete cascade,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  role text not null default 'owner',
  primary key (user_id, org_id)
);

create table if not exists public.geo_sessions (
  token text primary key,
  user_id bigint not null references public.geo_platform_users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.geo_password_reset_tokens (
  token_hash text primary key,
  user_id bigint not null references public.geo_platform_users(id) on delete cascade,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.geo_verified_domains (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  domain text not null,
  status text not null default 'pending',
  verify_token text not null,
  verify_method text not null default 'dns',
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (org_id, domain)
);

create table if not exists public.geo_org_competitors (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  domain text not null,
  unique (org_id, domain)
);

create table if not exists public.geo_org_prompts (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  external_id text not null default '',
  query_text text not null,
  query_class text not null default '',
  keyword_topic text not null default '',
  persona text not null default '',
  country text not null default '',
  unique (org_id, external_id)
);

create table if not exists public.geo_org_benchmark_runs (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  domain text not null,
  benchmark_run_id bigint not null,
  benchmark_score int not null,
  band text not null,
  run_at timestamptz not null,
  artifact_report_uri text default ''
);

create table if not exists public.geo_platform_runs (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  kind text not null,
  domain text not null,
  status text not null default 'queued',
  score int,
  band text not null default '',
  external_run_id text not null default '',
  error text not null default '',
  result_summary text not null default '',
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz
);

create table if not exists public.geo_page_audits (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  run_id bigint not null references public.geo_platform_runs(id) on delete cascade,
  domain text not null,
  page_url text not null,
  sitemap_url text not null default '',
  score int not null default 0,
  band text not null default '',
  http_status int,
  error text not null default '',
  score_breakdown_json jsonb not null default '{}'::jsonb,
  title_issues_json jsonb not null default '[]'::jsonb,
  meta_issues_json jsonb not null default '[]'::jsonb,
  schema_issues_json jsonb not null default '[]'::jsonb,
  recommendations_json jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.geo_agent_usage_events (
  id bigint generated by default as identity primary key,
  org_id bigint not null references public.geo_organizations(id) on delete cascade,
  domain text not null,
  page_url text not null default '',
  source_type text not null,
  agent text not null default '',
  query_text text not null default '',
  answer_excerpt text not null default '',
  cited_url text not null default '',
  cited_rank integer,
  surfaced boolean not null default false,
  cited boolean not null default false,
  top_recommendation boolean not null default false,
  confidence double precision not null default 1.0,
  value_units double precision not null default 0.0,
  evidence_artifact_id text not null default '',
  evidence_json text not null default '{}',
  created_at timestamptz not null default now()
);

alter table public.geo_agent_usage_events
